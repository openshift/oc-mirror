package fixtures

import (
	"fmt"
	"maps"
	"os"
	"path/filepath"

	v1 "github.com/google/go-containerregistry/pkg/v1"
	"sigs.k8s.io/yaml"
)

const (
	bundleManifestsDir = "manifests"
	bundleMetadataDir  = "metadata"
)

// bundleLabels are the labels of every bundle image, which annotations.yaml can override.
var bundleLabels = map[string]string{
	"operators.operatorframework.io.bundle.mediatype.v1": "registry+v1",
	"operators.operatorframework.io.bundle.manifests.v1": bundleManifestsDir + "/",
	"operators.operatorframework.io.bundle.metadata.v1":  bundleMetadataDir + "/",
}

// Bundle builds the operator bundle image of bundleDir for one platform, like the bundle
// Dockerfiles generated by operator-sdk:
//
//	FROM scratch
//	COPY manifests /manifests/
//	COPY metadata /metadata/
//	LABEL <the annotations of metadata/annotations.yaml>
func Bundle(bundleDir string, platform v1.Platform) (v1.Image, error) {
	data, err := os.ReadFile(filepath.Join(bundleDir, bundleMetadataDir, "annotations.yaml"))
	if err != nil {
		return nil, err
	}
	var metadata struct {
		Annotations map[string]string `json:"annotations"`
	}
	if err := yaml.Unmarshal(data, &metadata); err != nil {
		return nil, fmt.Errorf("failed to parse the annotations of %s: %w", bundleDir, err)
	}

	labels := maps.Clone(bundleLabels)
	maps.Copy(labels, metadata.Annotations)
	return build(nil, platform, []dirCopy{
		{src: filepath.Join(bundleDir, bundleManifestsDir), dest: bundleManifestsDir},
		{src: filepath.Join(bundleDir, bundleMetadataDir), dest: bundleMetadataDir},
	}, v1.Config{Labels: labels})
}
