package fixtures

import (
	"context"
	"fmt"
	"os"
	"path/filepath"

	v1 "github.com/google/go-containerregistry/pkg/v1"
	"github.com/operator-framework/operator-registry/pkg/cache"
	"golang.org/x/mod/modfile"
)

const (
	operatorRegistryModule = "github.com/operator-framework/operator-registry"
	opmRepository          = "quay.io/operator-framework/opm"

	// CatalogConfigsLabel points OLM and oc-mirror to the FBC root directory in a catalog image.
	CatalogConfigsLabel = "operators.operatorframework.io.index.configs.v1"
	catalogConfigsDir   = "/configs"
	catalogCacheDir     = "/tmp/cache"
	// opmUser is the user the opm image runs as, which owns the cache generated by opm.
	opmUser = 1001
)

// OPMImage returns the opm image whose opm binary matches the operator-registry module that
// generates the catalog caches, according to goMod, the go.mod file of the tests. This way the
// cache in a catalog image is the one its own opm would generate.
func OPMImage(goMod []byte) (string, error) {
	file, err := modfile.Parse("go.mod", goMod, nil)
	if err != nil {
		return "", err
	}
	for _, replace := range file.Replace {
		if replace.Old.Path == operatorRegistryModule {
			return "", fmt.Errorf("cannot determine the opm image of the replaced %s module", operatorRegistryModule)
		}
	}
	for _, require := range file.Require {
		if require.Mod.Path == operatorRegistryModule {
			return opmRepository + ":" + require.Mod.Version, nil
		}
	}
	return "", fmt.Errorf("%s is not required by go.mod", operatorRegistryModule)
}

// Catalog builds a file-based catalog image on top of base, an opm image, the same way as
// the catalog Dockerfiles generated by `opm generate dockerfile`:
//
//	CMD ["serve", "/configs", "--cache-dir=/tmp/cache"]
//	ADD <fbcDir> /configs
//	RUN ["/bin/opm", "serve", "/configs", "--cache-dir=/tmp/cache", "--cache-only"]
//	LABEL operators.operatorframework.io.index.configs.v1=/configs
//
// The serve cache is generated with the operator-registry library, which is what opm runs.
func Catalog(ctx context.Context, base v1.Image, fbcDir string) (v1.Image, error) {
	tmpDir, err := os.MkdirTemp("", "opm-cache-*")
	if err != nil {
		return nil, err
	}
	defer os.RemoveAll(tmpDir)
	cacheDir := filepath.Join(tmpDir, "cache")
	if err := serveCache(ctx, fbcDir, cacheDir); err != nil {
		return nil, fmt.Errorf("failed to generate the serve cache for %s: %w", fbcDir, err)
	}

	return build(base, v1.Platform{}, []dirCopy{
		{src: fbcDir, dest: catalogConfigsDir[1:]},
		{src: cacheDir, dest: catalogCacheDir[1:], owner: fileOwner{uid: opmUser}, dirModes: map[string]int64{"tmp": 0o1777}},
	}, v1.Config{
		Cmd:    []string{"serve", catalogConfigsDir, "--cache-dir=" + catalogCacheDir},
		Labels: map[string]string{CatalogConfigsLabel: catalogConfigsDir},
	})
}

// serveCache generates in cacheDir the cache `opm serve <fbcDir> --cache-only` creates.
func serveCache(ctx context.Context, fbcDir, cacheDir string) error {
	if err := os.Mkdir(cacheDir, 0o755); err != nil {
		return err
	}
	store, err := cache.New(cacheDir)
	if err != nil {
		return err
	}
	err = cache.LoadOrRebuild(ctx, store, os.DirFS(fbcDir))
	if closeErr := store.Close(); err == nil {
		err = closeErr
	}
	return err
}
