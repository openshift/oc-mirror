const (
	// cosignSignatureMediaType and cosignSignatureAnnotation define the cosign
	// signature format, read by containers/image as "sigstore attachments".
	cosignSignatureMediaType  = "application/vnd.dev.cosign.simplesigning.v1+json"
	cosignSignatureAnnotation = "dev.cosignproject.cosign/signature"
)

// loadCosignSigner loads a cosign private key without passphrase, as generated by
// `cosign generate-key-pair`.
func loadCosignSigner(keyPath string) (signature.Signer, error) {
	signer, err := signature.LoadSignerFromPEMFile(keyPath, crypto.SHA256, cryptoutils.StaticPasswordFunc([]byte("")))
	if err != nil {
		return nil, fmt.Errorf("loading cosign key %s: %w", keyPath, err)
	}
	return signer, nil
}

// sign attaches a cosign signature to the manifest with the given digest in repo,
// like `cosign sign --key <key> --tlog-upload=false` does: it pushes the signed
// payload as the "sha256-<digest>.sig" tag of the same repository.
func (b *builder) sign(repo string, digest v1.Hash) error {
	signed, err := name.NewDigest(SourceRegistry + "/" + repo + "@" + digest.String())
	if err != nil {
		return err
	}
	simpleSigning, err := payload.Cosign{Image: signed}.MarshalJSON()
	if err != nil {
		return fmt.Errorf("creating signature payload for %s: %w", signed, err)
	}
	sig, err := b.cosignSigner.SignMessage(bytes.NewReader(simpleSigning))
	if err != nil {
		return fmt.Errorf("signing %s: %w", signed, err)
	}

	sigImage := mutate.MediaType(empty.Image, types.OCIManifestSchema1)
	sigImage = mutate.ConfigMediaType(sigImage, types.OCIConfigJSON)
	sigImage, err = mutate.Append(sigImage, mutate.Addendum{
		Layer:       static.NewLayer(simpleSigning, cosignSignatureMediaType),
		Annotations: map[string]string{cosignSignatureAnnotation: base64.StdEncoding.EncodeToString(sig)},
	})
	if err != nil {
		return fmt.Errorf("creating signature image for %s: %w", signed, err)
	}

	sigTag := strings.Replace(digest.String(), ":", "-", 1) + ".sig"
	ref, err := b.reg.Reference(repo + ":" + sigTag)
	if err != nil {
		return err
	}
	if err := remote.Write(ref, sigImage, b.remoteOpts...); err != nil {
		return fmt.Errorf("pushing signature %s: %w", ref, err)
	}
	return nil
}

// signIndex signs an image index and each of its manifests, like
// `cosign sign --recursive` does.
func (b *builder) signIndex(repo string, idx v1.ImageIndex) error {
	digest, err := idx.Digest()
	if err != nil {
		return err
	}
	if err := b.sign(repo, digest); err != nil {
		return err
	}
	manifest, err := idx.IndexManifest()
	if err != nil {
		return err
	}
	for _, desc := range manifest.Manifests {
		if err := b.sign(repo, desc.Digest); err != nil {
			return err
		}
	}
	return nil
}

// releaseSignatureConfig matches `gpg --digest-algo SHA512`.
var releaseSignatureConfig = &packet.Config{DefaultHash: crypto.SHA512, RSABits: 2048}

// newReleaseSigner generates a throwaway GPG key to sign release payloads, like
// `gpg --quick-generate-key` does.
func newReleaseSigner() (*openpgp.Entity, error) {
	entity, err := openpgp.NewEntity("oc-mirror Release Test", "", "robot@test.com", releaseSignatureConfig)
	if err != nil {
		return nil, fmt.Errorf("generating release signing key: %w", err)
	}
	return entity, nil
}

// writeReleasePublicKey writes the armored public key of the release signer to path,
// like `gpg --armor --export` does.
func (b *builder) writeReleasePublicKey(path string) error {
	var buf bytes.Buffer
	w, err := armor.Encode(&buf, openpgp.PublicKeyType, nil)
	if err != nil {
		return err
	}
	if err := b.releaseSigner.Serialize(w); err != nil {
		return err
	}
	if err := w.Close(); err != nil {
		return err
	}
	return os.WriteFile(path, buf.Bytes(), 0o644)
}

// signRelease writes the signature of the release payload repoTag with the given
// digest to the release signatures directory, as "<tag>-sha256-<digest>": the file
// name oc-mirror uses for signatures in working-dir/signatures.
// The signature is an "atomic container signature" JSON payload signed with
// `gpg --sign`, the format OpenShift release signatures are published in.
func (b *builder) signRelease(repoTag string, digest string) error {
	hash, err := v1.NewHash(digest)
	if err != nil {
		return err
	}
	simpleSigning, err := json.Marshal(payload.SimpleContainerImage{
		Critical: payload.Critical{
			Identity: payload.Identity{DockerReference: SourceRegistry + "/" + repoTag},
			Image:    payload.Image{DockerManifestDigest: hash.String()},
			Type:     "atomic container signature",
		},
		Optional: map[string]any{},
	})
	if err != nil {
		return err
	}

	var signed bytes.Buffer
	w, err := openpgp.Sign(&signed, b.releaseSigner, nil, releaseSignatureConfig)
	if err != nil {
		return fmt.Errorf("signing release %s: %w", repoTag, err)
	}
	if _, err := w.Write(simpleSigning); err != nil {
		return err
	}
	if err := w.Close(); err != nil {
		return err
	}

	tag := repoTag[strings.LastIndex(repoTag, ":")+1:]
	name := fmt.Sprintf("%s-%s-%s", tag, hash.Algorithm, hash.Hex)
	return os.WriteFile(filepath.Join(b.releaseSignaturesDir, name), signed.Bytes(), 0o644)
}
